SKIP_PREFIX = ('Etc/', 'Antarctica/')


def parse_iso6709(s):
    m = re.match(r'([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$', s)
    sa, d1, m1, s1, so, d2, m2, s2 = m.groups()
    lat = int(d1) + int(m1)/60 + (int(s1 or 0))/3600
    lon = int(d2) + int(m2)/60 + (int(s2 or 0))/3600
    return (-lat if sa == '-' else lat), (-lon if so == '-' else lon)


def cldr_cities():
    from babel import Locale
    from babel.core import get_global
    tzn = Locale.parse('zh_Hans_CN').time_zones
    aliases = get_global('zone_aliases')          # 旧 ID -> 新 ID
    reverse = {}
    for old, new in aliases.items():
        reverse.setdefault(new, []).append(old)
    out = []
    zt = Path('/usr/share/zoneinfo/zone.tab')
    for line in zt.read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'):
            continue
        cc, coord, tz = line.split('\t')[:3]
        if tz.startswith(SKIP_PREFIX):
            continue
        name = None
        for key in [tz] + reverse.get(tz, []):
            v = tzn.get(key)
            if v and v.get('city'):
                name = v['city']; break
        if not name:
            continue
        lat, lon = parse_iso6709(coord)
        en = tz.split('/')[-1].replace('_', ' ')
        out.append((name, en, cc, round(lat, 3), round(lon, 3), 2))
    return out


