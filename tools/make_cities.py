    rows = {}
    for zh, en, cc, lat, lon, tier in SUPPLEMENT:
        rows[(zh, cc)] = [zh, en, cc, round(lon, 3), round(lat, 3), tier]
    for zh, en, cc, lat, lon, tier in cldr_cities():
        # 补充表优先；CLDR 名称与补充表同名同国家时跳过
        if (zh, cc) in rows or any(r[1] == en and r[2] == cc for r in rows.values()):
            continue
        rows[(zh, cc)] = [zh, en, cc, lon, lat, tier]
    data = sorted(rows.values(), key=lambda r: (r[5], r[2], r[1]))
    js = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
